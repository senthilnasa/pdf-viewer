#!/bin/bash
# ---------------------------------------------------------------
# PDF Viewer Platform — Docker Entrypoint
# Writes config files from environment variables, then starts Apache
# ---------------------------------------------------------------
set -e

echo "[pdfviewer] Starting configuration..."

CONFIG_DIR="/var/www/html/config"
DB_CONFIG="$CONFIG_DIR/database.php"
APP_CONFIG="$CONFIG_DIR/app.php"

# Write database config from environment variables.
# Values are exported with var_export() so quotes/backslashes in e.g. DB_PASS
# can't produce a PHP syntax error (which took the whole site down).
php -r '
$cfg = [
    "host"     => getenv("DB_HOST") ?: "db",
    "port"     => (int)(getenv("DB_PORT") ?: 3306),
    "name"     => getenv("DB_NAME") ?: "pdf_viewer",
    "username" => getenv("DB_USER") ?: "pdfviewer",
    "password" => getenv("DB_PASS") === false ? "" : getenv("DB_PASS"),
];
$out = "<?php\n// Auto-generated by Docker entrypoint — do not edit manually\nreturn [\n";
foreach ($cfg as $k => $v) { $out .= "    " . var_export($k, true) . " => " . var_export($v, true) . ",\n"; }
$out .= "    \x27charset\x27  => \x27utf8mb4\x27,\n"
      . "    \x27options\x27  => [\n"
      . "        PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,\n"
      . "        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,\n"
      . "        PDO::ATTR_EMULATE_PREPARES   => false,\n"
      . "    ],\n];\n";
file_put_contents($argv[1], $out);
' "$DB_CONFIG"

# Write app config only if it doesn't already exist (preserves manual edits)
if [ ! -f "$APP_CONFIG" ]; then
    php -r '
define("ROOT", "/var/www/html");
require ROOT . "/includes/Installer.php";
$php = file_get_contents(ROOT . "/config/app.php.example");
$php = Installer::setConfigValue($php, "base_url", getenv("APP_BASE_URL") ?: "http://localhost:8080");
file_put_contents($argv[1], $php);
' "$APP_CONFIG"
    echo "[pdfviewer] App config created from example."
fi

# Apply pending schema migrations (idempotent; skips if not installed yet)
php /var/www/html/migrate.php || echo "[pdfviewer] WARNING: migrations failed — see log above."

# Fix permissions
chown -R www-data:www-data /var/www/html/uploads /var/www/html/config
chmod -R 775 /var/www/html/uploads /var/www/html/config

echo "[pdfviewer] Config ready. Starting Apache..."

# Hand off to Apache
exec apache2-foreground "$@"
